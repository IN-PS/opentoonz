#!/usr/bin/env python3
"""Generate otm_glstub.h / glstub.cpp: no-op replacements for the legacy
desktop OpenGL/GLU entry points referenced by the OpenToonz core sources that
the mobile engine compiles.  Prototypes and constants are taken from the
Mesa GL/gl.h + GL/glu.h headers of the build machine (MIT licensed).
usage: gen_glstub.py <engine-dir>"""
import re, sys, os, glob
eng = os.path.abspath(sys.argv[1])
root = os.path.abspath(os.path.join(eng, '..', '..'))
src = os.path.join(root, 'toonz', 'sources')
cm = open(os.path.join(eng, 'CMakeLists.txt')).read()
files = [f.replace('${OT_COMMON}', src + '/common').replace('${OT_SRC}', src)
         for f in re.findall(r'\$\{OT_(?:COMMON|SRC)\}/[^\s)]+\.cpp', cm)]
files += glob.glob(src + '/include/*.h') + glob.glob(src + '/include/toonz/*.h')
files += glob.glob(src + '/common/*/*.h')
used = set()
for f in files:
    used |= set(re.findall(r'\b(?:glu?[A-Z]\w*|GLU?_[A-Z0-9_]+)\b', open(f, errors='ignore').read()))
hdr = open('/usr/include/GL/gl.h').read() + open('/usr/include/GL/glu.h').read() + \
      open('/usr/include/GL/glext.h').read()
protos = {}
for m in re.finditer(r'(?:GLAPI|extern)\s+([\w\s\*]+?)\s*(?:GLAPIENTRY|APIENTRY|GLAPIENTRYP)?\s+(glu?\w+)\s*\(([^;]*?)\)\s*;', hdr, re.S):
    ret, name, args = m.group(1).strip(), m.group(2), ' '.join(m.group(3).split())
    if name not in protos: protos[name] = (ret, args)
consts = {}
for m in re.finditer(r'#define\s+(GLU?_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|-?\d+)\b', hdr):
    consts.setdefault(m.group(1), m.group(2))
types = '''typedef unsigned int GLenum; typedef unsigned char GLboolean; typedef unsigned int GLbitfield;
typedef void GLvoid; typedef signed char GLbyte; typedef short GLshort; typedef int GLint;
typedef unsigned char GLubyte; typedef unsigned short GLushort; typedef unsigned int GLuint;
typedef int GLsizei; typedef float GLfloat; typedef float GLclampf; typedef double GLdouble;
typedef double GLclampd; typedef char GLchar; typedef long GLsizeiptr; typedef long GLintptr;
class GLUnurbs; class GLUquadric; class GLUtesselator; typedef GLUnurbs GLUnurbsObj;
typedef GLUquadric GLUquadricObj; typedef GLUtesselator GLUtesselatorObj; typedef GLUtesselator GLUtriangulatorObj;
typedef void (*_GLUfuncptr)(void);
'''
H = ['#pragma once', '// Generated by android/tools/gen_glstub.py - do not edit.',
     '// No-op stand-ins for desktop OpenGL/GLU used by OpenToonz core code', '// compiled for OpenToonz Mobile (CPU rendering path).', types,
     '#define GLAPIENTRY', '#define GLUT_STROKE_ROMAN ((void *)0)', '#define CALLBACK', '#define APIENTRY']
C = ['// Generated by android/tools/gen_glstub.py - do not edit.', '#include "otm_glstub.h"', '']
for c in sorted(used):
    if c in consts: H.append('#define %s %s' % (c, consts[c]))
missing = []
for f in sorted(used):
    if f in protos:
        ret, args = protos[f]
        H.append('%s %s(%s);' % (ret, f, args))
        body = '' if ret == 'void' else ' return (%s)0;' % ret
        C.append('%s %s(%s) {%s}' % (ret, f, args, body))
    elif f not in consts and not f.startswith('GL'):
        missing.append(f)
open(os.path.join(eng, 'compat', 'otm_glstub.h'), 'w').write('\n'.join(H) + '\n')
open(os.path.join(eng, 'compat', 'glstub.cpp'), 'w').write('\n'.join(C) + '\n')
print('stubbed %d functions; unknown identifiers: %s' % (len(C) - 3, ' '.join(missing)))
